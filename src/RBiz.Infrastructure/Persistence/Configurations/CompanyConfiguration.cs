using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using RBiz.Domain.Entities;
using RBiz.Infrastructure.Persistence.Sync;

namespace RBiz.Infrastructure.Persistence.Configurations;

/// <summary>Schema for <see cref="Company"/>.</summary>
internal sealed class CompanyConfiguration : IEntityTypeConfiguration<Company>
{
    public void Configure(EntityTypeBuilder<Company> builder)
    {
        builder.ToTable("Companies");

        builder.HasKey(c => c.Id);

        // Row version, tombstone columns, delta index and soft-delete filter.
        builder.ConfigureSyncable();

        builder.Property(c => c.Name)
            .HasMaxLength(200)
            .IsRequired();

        builder.Property(c => c.GstStatus)
            .HasConversion<int>()
            .HasDefaultValue(GstRegistrationStatus.NotRegistered);

        builder.Property(c => c.IsActive)
            .HasDefaultValue(true);

        // Makes a replayed creation request find the company the first attempt made,
        // rather than creating a second set of books for the same business. Scoped to the
        // creator because the id is generated by that client.
        builder.HasIndex(c => new { c.CreatedBy, c.CreationRequestId })
            .IsUnique()
            .HasDatabaseName("UX_Companies_Creator_RequestId");

        builder.HasOne(c => c.Address)
            .WithOne(a => a.Company!)
            .HasForeignKey<CompanyAddress>(a => a.CompanyId)
            .OnDelete(DeleteBehavior.Cascade);

        builder.HasOne(c => c.GstRegistration)
            .WithOne(g => g.Company!)
            .HasForeignKey<CompanyGstRegistration>(g => g.CompanyId)
            .OnDelete(DeleteBehavior.Cascade);
    }
}
