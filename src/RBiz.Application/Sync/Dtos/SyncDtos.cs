namespace RBiz.Application.Sync.Dtos;

/// <summary>What a client wants done to a row.</summary>
public enum SyncChangeType
{
    Upsert = 1,
    Delete = 2
}

/// <summary>How the server answered one pushed change.</summary>
public enum SyncResultStatus
{
    /// <summary>Stored. The client can drop it from its outbox.</summary>
    Applied = 1,

    /// <summary>
    /// Someone else changed the row first. The client gets the current server row and
    /// decides what to do; nothing was overwritten.
    /// </summary>
    Conflict = 2,

    /// <summary>Invalid or not permitted. Retrying unchanged will not help.</summary>
    Rejected = 3,

    /// <summary>
    /// Already applied by an earlier attempt at the same operation. Reported separately
    /// from Applied so a client can tell a genuine save from a replayed one.
    /// </summary>
    Duplicate = 4
}

/// <summary>
/// One row in a delta, as sent to a client. Payload is the entity's own JSON shape;
/// a tombstone carries no payload.
/// </summary>
public sealed record SyncEntityChange(
    Guid Id,
    SyncChangeType ChangeType,
    string? RowVersion,
    DateTime? ModifiedAtUtc,
    object? Payload);

/// <summary>Changes for one entity type, plus where its stream now stands.</summary>
public sealed record SyncEntityChangeSet(
    string Entity,
    IReadOnlyList<SyncEntityChange> Changes,
    string? NextCursor,
    bool HasMore);

/// <summary>
/// Response to a pull. Each entity carries its own cursor because the entities are
/// paged independently: a large Billing backlog must not hold up Stock.
/// </summary>
public sealed record SyncPullResponse(
    IReadOnlyList<SyncEntityChangeSet> Entities,
    DateTime ServerTimeUtc)
{
    /// <summary>True when at least one entity still has changes waiting.</summary>
    public bool HasMore => Entities.Any(e => e.HasMore);
}

/// <summary>
/// One change a client is pushing up.
/// </summary>
/// <param name="OperationId">
/// Client-generated id, reused on every retry of this same change. This is what makes
/// the push idempotent, so it is required.
/// </param>
/// <param name="Entity">Entity name, e.g. "users".</param>
/// <param name="Id">Primary key of the row, generated by the client while offline.</param>
/// <param name="ChangeType">Whether the row is being upserted or deleted.</param>
/// <param name="BaseRowVersion">
/// The row version the client last saw. Null means "I believe this row is new". A
/// mismatch against the server's current version is reported as a conflict.
/// </param>
/// <param name="Payload">
/// The row's fields. Null for a delete. Sent as a loose dictionary so each provider
/// validates and maps only the fields it allows a client to set.
/// </param>
public sealed record SyncPushItem(
    Guid OperationId,
    string Entity,
    Guid Id,
    SyncChangeType ChangeType,
    string? BaseRowVersion,
    Dictionary<string, object?>? Payload);

/// <summary>A batch of changes from one device.</summary>
public sealed record SyncPushRequest(string DeviceId, IReadOnlyList<SyncPushItem> Items);

/// <summary>
/// Outcome for one pushed change. On a conflict, <paramref name="ServerRow"/> holds the
/// server's current version so the client can merge without a second round trip.
/// </summary>
public sealed record SyncPushItemResult(
    Guid OperationId,
    Guid Id,
    string Entity,
    SyncResultStatus Status,
    string? RowVersion,
    string? Message,
    object? ServerRow);

/// <summary>
/// Response to a push. Individual failures do not fail the batch: a single bad row must
/// not block a device from draining the rest of its outbox.
/// </summary>
public sealed record SyncPushResponse(
    IReadOnlyList<SyncPushItemResult> Results,
    DateTime ServerTimeUtc)
{
    public int AppliedCount => Results.Count(r => r.Status is SyncResultStatus.Applied);

    public int ConflictCount => Results.Count(r => r.Status is SyncResultStatus.Conflict);

    public int RejectedCount => Results.Count(r => r.Status is SyncResultStatus.Rejected);
}

/// <summary>
/// Lightweight state probe. A PWA uses this to confirm it really has connectivity to
/// this API - navigator.onLine only reports that a network interface exists, not that
/// the server is reachable - and to measure its clock offset before queueing work.
/// </summary>
public sealed record SyncStatusResponse(
    DateTime ServerTimeUtc,
    IReadOnlyList<string> SyncableEntities,
    int MaxPullPageSize,
    int MaxPushBatchSize);
